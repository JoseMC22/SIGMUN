function toText(value: unknown): string {
  return value === null || value === undefined ? '' : String(value);
}

function toNumber(value: unknown): number {
  const parsed = Number(value ?? 0);
  return Number.isFinite(parsed) ? parsed : 0;
}

/**
 * Reads one cell from the named recordset by column name. A key without a
 * mapping is an explicit error: it must never be silenced as an empty cell.
 */
function readSpField(row: SpConsultaPrediosRow, key: string): unknown {
  const field = SP_FIELD_BY_KEY[key];
  if (field === undefined) {
    throw new Error(`consulta-predios: no SP column mapping for key "${key}"`);
  }
  return row[field];
}

/** Name-based mapping of the @busc=19 SELECT, verified against the live SP. */
export function mapConsultaPredioRow(
  row: SpConsultaPrediosRow,
): ConsultaPrediosRow {
  const cells = row ?? {};
  return {
    codigo: toText(readSpField(cells, 'codigo')),
    nombre: toText(readSpField(cells, 'nombre')),
    cod_pred: toText(readSpField(cells, 'cod_pred')),
    anexo: toText(readSpField(cells, 'anexo')),
    direccion: toText(readSpField(cells, 'direccion')),
    uso: toText(readSpField(cells, 'uso')),
    t_area_const: toNumber(readSpField(cells, 't_area_const')),
    area_terreno: toNumber(readSpField(cells, 'area_terreno')),
    porcen: toNumber(readSpField(cells, 'porcen')),
    val_terreno: toNumber(readSpField(cells, 'val_terreno')),
    val_constru: toNumber(readSpField(cells, 'val_constru')),
    autoavaluo: toNumber(readSpField(cells, 'autoavaluo')),
    id_instalas: toText(readSpField(cells, 'id_instalas')),
    num_pisos: toNumber(readSpField(cells, 'num_pisos')),
    categoria: toText(readSpField(cells, 'categoria')),
  };
}

@Injectable()
export class ConsultaPrediosService {
  constructor(private readonly db: DatabaseService) {}

  /**
   * `@busc=20` returns the total under the `''` key of the first row, while
   * `@busc=19` returns the paginated rows as named objects. All values are
   * bound as named parameters and never concatenated into the query.
   */
  async search(
    dto: SearchConsultaPrediosDto,
  ): Promise<ConsultaPrediosSearchResponse> {
    const {
      codigo,
      codPred,
      anno,
      codVia,
      urbBus,
      nro,
      dpto,
      mza,
      lte,
      sublote,
      page,
      pageSize,
    } = dto;

    const inicio = (page - 1) * pageSize + 1;
    const final = inicio + pageSize - 1;

    const totalResult = await this.db.executeProcedure<SpConsultaPrediosRow>(
      SP_MCONTRIBUYENTE,
      {
        'busc': 20,
        'anno': anno,
        'id_via': codVia,
        'nro': nro,
        'dpto': dpto,
        'Mza': mza,
        'Lte': lte,
        'SubLte': sublote,
        'cod_pred': codPred,
        'codigo': codigo,
        'cod_urb': urbBus,
      },
    );

    const total = toNumber(totalResult.recordset?.[0]?.['']);

    const rowsResult = await this.db.executeProcedure<SpConsultaPrediosRow>(
      SP_MCONTRIBUYENTE,
      {
        'busc': 19,
        'anno': anno,
        'id_via': codVia,
        'nro': nro,
        'dpto': dpto,
        'Mza': mza,
        'Lte': lte,
        'SubLte': sublote,
        'cod_pred': codPred,
        'codigo': codigo,
        'inicio': inicio,
        'final': final,
        'cod_urb': urbBus,
      },
    );

    const data = (rowsResult.recordset ?? []).map((row) =>
      mapConsultaPredioRow(row),
    );
    const totalPages = total > 0 ? Math.ceil(total / pageSize) : 0;

    return { data, total, page, pageSize, totalPages };
  }

  /**
   * `@busc='21'` returns report rows as named objects. The title is read from
   * the `anno` key (the frontend prepends its own prefix) and is never emitted
   * as data; `@flag_pisos='1'` adds 17 columns. All values are bound as named
   * parameters.
   */
  async exportPredios(
    dto: ExportConsultaPrediosDto,
  ): Promise<ConsultaPrediosExportResponse> {
    const {
      codigo,
      codPred,
      anno,
      codVia,
      urbBus,
      nro,
      dpto,
      mza,
      lte,
      sublote,
      mostrarPisos,
    } = dto;

    const result = await this.db.executeProcedure<SpConsultaPrediosRow>(
      SP_MCONTRIBUYENTE,
      {
        'busc': '21',
        'codigo': codigo,
        'cod_pred': codPred,
        'id_via': codVia,
        'cod_urb': urbBus,
        'anno': anno,
        'nro': nro,
        'dpto': dpto,
        'Mza': mza,
        'Lte': lte,
        'SubLte': sublote,
        'flag_pisos': mostrarPisos ? '1' : '0',
      },
    );

    const spRows = result.recordset ?? [];
    const columns = mostrarPisos
      ? [...EXPORT_BASE_COLUMNS, ...EXPORT_PISO_COLUMNS]
      : EXPORT_BASE_COLUMNS;
    const dataColumns = columns.slice(1);

    const rows = spRows.map((row, index) => {
      const cells = row ?? {};
      return [
        String(index + 1),
        ...dataColumns.map((column) => toText(readSpField(cells, column.key))),
      ];
    });

    return {
      title: toText(spRows[0]?.['anno']),
      mostrarPisos,
      columns: [...columns],
      rows,
    };
  }
}
